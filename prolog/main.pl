% Директива (команда для интерпретатора): файл записан в кодировке UTF-8, чтобы русские буквы читались верно
:- encoding(utf8).

% Prolog — язык логического программирования: мы описываем ФАКТЫ и ПРАВИЛА, а потом задаём вопросы
% Ниже — исходные данные из пункта 3.1 задания в виде факта student/5 (/5 значит «5 аргументов»)
% Факт: слово student и в скобках 5 значений — ФИО по-русски, ФИО латиницей, номер в списке,
student('Калмыков Ярослав Владимирович', 'Kalmykov Yaroslav Vladimirovich', 8,
        % ...группа и название языка; точка в конце означает конец факта
        'М3О-110БВк-26', 'Prolog').

% Факт: номер кафедры равен 304
department(304).

% Правило (:- читается как «если»): контрольное значение V вычисляется из факта student/5
control_value(V) :-
    % Берём из факта номер N; символ _ означает «это значение нам не нужно»
    student(_, _, N, _, _),
    % Берём номер кафедры D
    department(D),
    % is вычисляет выражение справа и записывает результат в V (304 * 8 = 2432)
    V is D * N.

% Правило: идентификатор Id = группа + "/" + номер (минимум две цифры)
student_id(Id) :-
    % Берём из факта номер N и название группы Group
    student(_, _, N, Group, _),
    % format(atom(Num), ...) превращает число N в текст Num; шаблон ~`0t~d~2| дополняет число нулями слева до ширины 2 (8 -> 08)
    format(atom(Num), '~`0t~d~2|', [N]),
    % Склеиваем группу, символ "/" и текст номера в одну строку Id
    atomic_list_concat([Group, '/', Num], Id).

% Главное правило: его мы вызываем для запуска программы
main :-
    % Достаём все 5 значений из факта в переменные (переменные в Prolog пишутся с большой буквы)
    student(NameRu, NameEn, N, Group, Lang),
    % Достаём номер кафедры в переменную D
    department(D),
    % Обращаемся к правилу control_value: результат попадёт в V
    control_value(V),                   % запрос к правилу
    % Обращаемся к правилу student_id: результат попадёт в Id
    student_id(Id),
    % format печатает по шаблону: ~d — целое число, ~w — любое значение, ~n — новая строка; значения берутся из списка в []
    format("Hello to ~d from ~w, number ~d, group ~w!~n", [D, NameEn, N, Group]),
    % То же самое по-русски
    format("Привет, ~d! Это ~w, номер ~d, группа ~w!~n", [D, NameRu, N, Group]),
    % Строка с student_id, языком и контрольным числом; точка в конце — конец правила main
    format("Student ID: ~w | Language: ~w | Control: ~d~n", [Id, Lang, V]).
