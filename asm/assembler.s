# macOS Apple Silicon (arm64 / AArch64), нативный Apple Clang
# Assembler — это «почти машинный код»: каждая строка — одна команда процессору. Комментарии после // относятся к строке слева
# Начинаем раздел данных: сюда кладём текстовые строки только для чтения
.section __TEXT,__cstring,cstring_literals
// Метка message — «имя» адреса, где лежит наш текст (по ней потом найдём строку)
message:
    // .asciz кладёт в память текст и добавляет в конец нулевой байт, по которому функция печати узнаёт, где текст кончается
    .asciz "Hello to 304 from Kalmykov Yaroslav Vladimirovich, number 8, group M3O-110BVk-26!"

# Начинаем раздел с программным кодом (командами процессора)
.section __TEXT,__text,regular,pure_instructions
// Делаем метку _main видимой снаружи: с неё система начнёт запуск программы
.globl _main

// Метка _main — начало главной функции
_main:
    // stp сохраняет в стек два регистра (x29 и x30) — запоминаем, куда вернуться после работы (стек — «блокнот» в памяти)
    stp x29, x30, [sp, #-16]!
    // mov копирует значение: x29 = sp, фиксируем текущую позицию в стеке
    mov x29, sp
    // adrp загружает в x0 адрес страницы памяти, где лежит message
    adrp x0, message@PAGE
    // add прибавляет смещение внутри страницы: теперь x0 хранит точный адрес текста (x0 — первый аргумент функции)
    add x0, x0, message@PAGEOFF
    // bl вызывает функцию _puts из стандартной библиотеки C: она печатает текст по адресу из x0 и добавляет перевод строки
    bl _puts
    // Кладём 0 в w0 — это код возврата «программа завершилась без ошибок»
    mov w0, #0
    // ldp достаёт из стека сохранённые регистры обратно и сдвигает стек на место
    ldp x29, x30, [sp], #16
    // ret — возврат из функции, программа завершается
    ret
