// Подключаем стандартную библиотеку ввода-вывода: из неё нам нужна функция printf (вывод текста на экран)
#include <stdio.h>

// Проверка при сборке: если программу компилируют под Windows (там задан макрос _WIN32)...
#ifdef _WIN32
// ...подключаем системную библиотеку Windows, она нужна только чтобы настроить кодировку консоли
#include <windows.h>
// Конец блока, который работает только в Windows
#endif

// main — главная функция: с неё начинается выполнение любой программы на C; int — вернёт число, void — параметров нет
int main(void) {
// Снова проверка: этот кусок кода будет собран только под Windows
#ifdef _WIN32
    // Говорим консоли Windows, что ввод идёт в кодировке UTF-8
    SetConsoleCP(CP_UTF8);
    // Говорим консоли, что вывод тоже в UTF-8, иначе русские буквы превратятся в «кракозябры»
    SetConsoleOutputCP(CP_UTF8);
// Конец блока только для Windows
#endif

    // Комментарий-заголовок: ниже идут исходные данные из пункта 3.1 задания
    // Строка (указатель на текст) с ФИО по-русски; const — значение менять нельзя
    const char *student_name_ru = "Калмыков Ярослав Владимирович";
    // Строка с ФИО латиницей
    const char *student_name_en = "Kalmykov Yaroslav Vladimirovich";
    // Целое число (int) — мой номер в списке группы
    const int   student_number  = 8;
    // Строка с названием группы
    const char *group_name      = "М3О-110БВк-26";
    // Строка с названием языка программирования
    const char *language_name   = "C";
    // Целое число — номер кафедры
    const int   department      = 304;

    // Вычисляем контрольное значение: номер кафедры умножаем на номер в списке (304 * 8 = 2432)
    const int control_value = department * student_number;

    // printf печатает текст; %d — сюда подставится целое число, %s — сюда подставится строка
    printf("Hello to %d from %s, number %d, group %s!\n",
           // Подставляем по порядку: номер кафедры (в первый %d) и английское ФИО (в первый %s)
           department, student_name_en, student_number, group_name);
    // Вторая печать: то же самое, но по-русски; \n в конце — переход на новую строку
    printf("Привет, %d! Это %s, номер %d, группа %s!\n",
           // Значения для четырёх мест подстановки: число, строка, число, строка
           department, student_name_ru, student_number, group_name);
    // %02d выводит число минимум из 2 цифр, добавляя спереди ноль (8 станет 08)
    printf("Student ID: %s/%02d | Language: %s | Control: %d\n",
           // Значения подставляются по порядку: группа, номер, язык, контрольное число
           group_name, student_number, language_name, control_value);

    // Возвращаем 0 — это сигнал операционной системе «программа завершилась без ошибок»
    return 0;
// Закрывающая скобка — конец функции main
}
